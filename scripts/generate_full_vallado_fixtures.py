def generate():
    offsets = [0.0, 360.0, 1440.0]
    out_data = []

    for sat_info in VALLADO_SATELLITES:
        satrec = Satrec.twoline2rv(sat_info["tle1"], sat_info["tle2"], WGS72)
        benchmarks = []
        
        for offset_min in offsets:
            err, r, v = satrec.sgp4_tsince(offset_min)
            assert err == 0
            benchmarks.append({
                "offset_min": offset_min,
                "r_ref": [float(val) for val in r],
                "v_ref": [float(val) for val in v]
            })
            
        out_data.append({
            "name": sat_info["name"],
            "norad_id": sat_info["norad_id"],
            "tle1": sat_info["tle1"],
            "tle2": sat_info["tle2"],
            "benchmarks": benchmarks
        })

    fixture_path = Path("tests/fixtures/sgp4_ver_reference.json").resolve()
    with open(fixture_path, "w", encoding="utf-8") as f:
        json.dump(out_data, f, indent=2)

    print(f"Generated complete 24-satellite Vallado benchmark reference fixture at: {fixture_path}")
    print(f"Total Satellites: {len(out_data)} | Total Test Vectors: {len(out_data) * len(offsets)}")

if __name__ == "__main__":
    generate()
